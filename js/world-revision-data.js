const revisionsById=new Map(WORLD_REVISIONS.map(row=>[row.id,row]));
export function reviseWorldDefinitions(rows){
 return rows.map(row=>{
  const revision=revisionsById.get(row.id);
  if(!revision)return row;
  // 基準以外の本文を上書きせず、既に適用済みならそのまま返す。
  if(row.text!==revision.beforeText)return row;
  return {...row,text:revision.text,titleWord:revision.titleWord};
 });
}
